#!/usr/bin/env python3
"""Original finite-Fourier saw tables, generated from mathematical sine sums."""
import math
from pathlib import Path
import sys
root = Path(__file__).resolve().parents[1]
harmonics = [1, 2, 4, 8, 16, 32, 64]
lines = ['// SPDX-License-Identifier: MIT', '// Generated by tools/generate_brass_tables.py; no borrowed samples or tables.',
         '#pragma once', '#include <cstdint>', 'namespace tone_noise::detail {',
         '// clang-format off', 'constexpr unsigned kBrassHarmonics[7] = {1, 2, 4, 8, 16, 32, 64};',
         'constexpr int16_t kBrassSaw[7][257] = {']
for count in harmonics:
    values = [sum(math.sin(2*math.pi*h*i/256)/h for h in range(1,count+1)) for i in range(256)]
    scale = 32767/max(abs(x) for x in values)
    ints = [round(x*scale) for x in values]
    ints.append(ints[0])
    lines.append('    {')
    for base in range(0,len(ints),12):
        lines.append('        '+', '.join(str(x) for x in ints[base:base+12])+(',' if base+12<len(ints) else ''))
    lines.append('    },')
lines += ['};', '// clang-format on', '}  // namespace tone_noise::detail', '']
text = '\n'.join(lines)
path = root/'src/brass_wavetables.h'
if '--check' in sys.argv:
    if path.read_text() != text: raise SystemExit('brass tables differ from generator')
else:
    path.write_text(text)
